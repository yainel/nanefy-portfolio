  var KEY = 'yg-lang';
  function pick() {
    var q = new URLSearchParams(location.search).get('lang');
    if (q === 'en' || q === 'es') { try { localStorage.setItem(KEY, q); } catch (e) {} return q; }
    try { var s = localStorage.getItem(KEY); if (s === 'en' || s === 'es') return s; } catch (e) {}
    return /^es\b/i.test(navigator.language || '') ? 'es' : 'en';
  }
  var lang = pick();

  window.ygLang = lang;
  window.ygT = function (s, vars) {
    var out = lang === 'es' && es[s] || s;
    if (vars) Object.keys(vars).forEach(function (k) { out = out.replace('{' + k + '}', vars[k]); });
    return out;
  };
  window.ygSetLang = function (l) {
    try { localStorage.setItem(KEY, l); } catch (e) {}
    var url = new URL(location.href);
    url.searchParams.set('lang', l);
    location.replace(url.toString()); // reload so every demo starts in the new language
  };

  document.documentElement.lang = lang;
  var btn = document.getElementById('langBtn');
  if (btn) {
    btn.textContent = lang === 'es' ? 'EN' : 'ES';
    btn.setAttribute('aria-label', lang === 'es' ? 'Switch to English' : 'Cambiar a español');
    btn.setAttribute('data-tip', lang === 'es' ? 'English' : 'Español');
    btn.addEventListener('click', function () { window.ygSetLang(lang === 'es' ? 'en' : 'es'); });
  }
  if (lang !== 'es') return;

  // Swap text nodes and labels. Leading and trailing spaces are kept so inline text still flows.
  var walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT), node;
  while ((node = walker.nextNode())) {
    var p = node.parentElement;
    if (!p || p.closest('script,style,code,pre,#pgRoot')) continue;
    var raw = node.nodeValue, key = raw.replace(/\s+/g, ' ').trim();
    if (key && es[key]) node.nodeValue = raw.match(/^\s*/)[0] + es[key] + raw.match(/\s*$/)[0];
  }
  // Short labels where the full translation would not fit, like the sidebar: <a data-es="Proyectos">
  document.querySelectorAll('[data-es]').forEach(function (el) {
    var text = [].filter.call(el.childNodes, function (n) { return n.nodeType === 3 && n.nodeValue.trim(); })[0];
    if (text) text.nodeValue = el.dataset.es;
  });
  ['placeholder', 'aria-label', 'data-tip', 'title'].forEach(function (a) {
    document.querySelectorAll('[' + a + ']').forEach(function (el) {
      if (el.id === 'langBtn') return;
      var v = el.getAttribute(a);
      if (es[v]) el.setAttribute(a, es[v]);
    });
  });
